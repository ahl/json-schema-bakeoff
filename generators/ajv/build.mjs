//! `build.mjs <gen_dir> <batch_dir>`: the build step of the generator
//! contract for ajv.
//!
//! Reads a JSON array of module keys on stdin and prints
//! `{"outcomes": {key: "ok" | {"fail": diagnostic}}, "runner": [exe, args]}`.
//! Everything else goes to stderr.
//!
//! There is nothing to compile — the modules are JavaScript and ajv
//! compiles the schema itself, lazily, at run time — so "build" here is
//! copying the modules into the batch directory, loading each one to prove
//! it loads, and writing the runner that drives them. Loading is done one
//! module at a time precisely so a module that fails to load is attributed
//! to its own key, the way a compiler diagnostic would be, instead of
//! taking the batch down.

import { ensureDeps, quietStdout, writeAll } from "./deps.mjs";
import { createRequire } from "node:module";
import { copyFileSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** Cap on stored diagnostic text per module; these end up in results.json. */
const MAX_DIAG_LEN = 4000;

const [, , genDir, batchDir] = process.argv;
if (!genDir || !batchDir) {
  process.stderr.write("usage: build.mjs <gen_dir> <batch_dir>\n");
  process.exit(2);
}

const chunks = [];
for await (const chunk of process.stdin) chunks.push(chunk);
// A module key is derived from the schema, so two suite files holding the
// same schema share one; the harness dedupes, but don't depend on it.
const keys = [...new Set(JSON.parse(Buffer.concat(chunks).toString("utf8")))];

// stdout is the protocol from here on.
quietStdout();
ensureDeps();

function truncate(s, max = MAX_DIAG_LEN) {
  return s.length <= max ? s : `${s.slice(0, max)}\n... (truncated)`;
}

/**
 * The runner, written into the batch directory.
 *
 * Modules are required on first use rather than all at once, so a draft
 * whose cases only touch some of them pays only for those, and a runner
 * restarted after a dead case doesn't reload the whole batch.
 */
function runnerSource(alive) {
  return `// Generated by the bakeoff harness. See DESIGN.md for the runner protocol.
"use strict";

const fs = require("fs");
const path = require("path");

const ALIVE = new Set(${JSON.stringify(alive)});
const LOADED = new Map();

/**
 * The module for a key, or the error that stopped it loading — memoized
 * either way, so a module that won't load costs one attempt and not one
 * per case. A load failure is the module's, not the instance's, so the
 * caller reports it as a panic rather than as a rejected instance.
 */
function moduleFor(key) {
  if (!LOADED.has(key)) {
    try {
      LOADED.set(key, { mod: require(path.join(__dirname, key + ".js")) });
    } catch (e) {
      LOADED.set(key, { error: e && e.message ? String(e.message) : String(e) });
    }
  }
  return LOADED.get(key);
}

/**
 * JSON.parse that converts each number from the exact digits the harness
 * wrote, by way of the reviver's source text, rather than letting the
 * parser reach them first.
 *
 * It lands on the same float64 either way — this is what JavaScript's own
 * JSON parser does, and \`Number(source)\` is defined to agree with it —
 * but it puts the lossy step in one visible place. ajv validates parsed
 * JavaScript values and nothing else, so an integer past 2^53 reaches it
 * rounded; that is the finding, not a harness artifact. See README.md.
 */
function parseCases(text) {
  return JSON.parse(text, function (_key, value, context) {
    if (typeof value === "number" && context && typeof context.source === "string") {
      return Number(context.source);
    }
    return value;
  });
}

/**
 * The reviver's third argument arrived in Node 21. Here the fallback is
 * harmless — the plain parser produces the same float64 — but if it is
 * missing then the *generate* step's number handling is broken too, so
 * say so instead of running on quietly.
 */
function requireSourceReviver() {
  let seen = false;
  JSON.parse("[1]", function (_k, v, context) {
    if (typeof v === "number" && context && typeof context.source === "string") seen = true;
    return v;
  });
  if (!seen) {
    fs.writeSync(2, "runner: this Node has no JSON.parse source-text reviver; need Node 21+\\n");
    process.exit(2);
  }
}

function emit(value) {
  // stdout is a pipe, where process.stdout.write is asynchronous and the
  // harness may be waiting on this very line. writeSync on a pipe can stop
  // short (and raise EAGAIN once the pipe is full), so loop: half a line of
  // JSON is a line the harness can't parse.
  const buf = Buffer.from(JSON.stringify(value) + "\\n", "utf8");
  let off = 0;
  while (off < buf.length) {
    try {
      off += fs.writeSync(1, buf, off, buf.length - off);
    } catch (e) {
      if (!e || e.code !== "EAGAIN") throw e;
    }
  }
}

function main() {
  if (process.argv.length !== 4) {
    fs.writeSync(2, "usage: runner <cases.json> <start-index>\\n");
    process.exit(2);
  }
  requireSourceReviver();
  const cases = parseCases(fs.readFileSync(process.argv[2], "utf8"));
  const start = parseInt(process.argv[3], 10);

  emit({ ready: start });
  for (let i = start; i < cases.length; i++) {
    const key = cases[i].key;
    let outcome;
    const entry = ALIVE.has(key) ? moduleFor(key) : null;
    if (entry === null) {
      outcome = { panic: "module not compiled" };
    } else if (entry.error !== undefined) {
      // Loading is not validating: a module that won't load says nothing
      // about the instance, so it must not read as a rejection.
      outcome = { panic: "module failed to load: " + entry.error };
    } else {
      try {
        entry.mod.__conformanceCheck(cases[i].data);
        outcome = "accept";
      } catch (e) {
        // An invalid instance arrives as the Error \`__conformanceCheck\`
        // builds from ajv's \`errorsText\`, so a reject is the default. A
        // RangeError is not that: it is ajv's generated validator
        // recursing until the stack goes, which is a crash that happened
        // to be catchable. Calling it a panic keeps it alongside the Rust
        // rows, where the same schema takes the process down and the
        // harness records a panic for it.
        const message = e && e.message ? String(e.message) : String(e);
        outcome = e instanceof RangeError ? { panic: message } : { reject: message };
      }
    }
    emit({ case: { i: i, r: outcome } });
  }
}

main();
`;
}

function build() {
  // Start clean so the batch directory says what was actually built.
  rmSync(batchDir, { recursive: true, force: true });
  mkdirSync(batchDir, { recursive: true });
  // The batch lives under target/, which has no package.json, so Node
  // treats these as CommonJS. Say so rather than relying on it.
  writeFileSync(join(batchDir, "package.json"), '{ "type": "commonjs" }\n');
  for (const key of keys) copyFileSync(join(genDir, `${key}.js`), join(batchDir, `${key}.js`));

  // Load every module once, here, so that a module which cannot be loaded
  // is this key's failure and not a mystery in the runner. Loading does
  // not compile the schema — that is lazy, on the first case — so this is
  // cheap and still catches a module that isn't valid JavaScript.
  const require_ = createRequire(join(batchDir, "noop.cjs"));
  const failures = {};
  const alive = [];
  for (const key of keys) {
    const path = join(batchDir, `${key}.js`);
    try {
      require_(path);
      alive.push(key);
    } catch (e) {
      failures[key] = e instanceof Error ? `${e.name}: ${e.message}` : String(e);
    } finally {
      // Node keys the require cache by realpath, so resolve before
      // deleting: a symlink anywhere above the batch directory would make
      // a delete on the literal path a silent no-op.
      try {
        delete require_.cache[require_.resolve(path)];
      } catch {
        // Never loaded, or already gone.
      }
    }
  }
  if (Object.keys(failures).length > 0) {
    process.stderr.write(`ajv: ${Object.keys(failures).length} module(s) failed to load\n`);
  }

  writeFileSync(join(batchDir, "runner.js"), runnerSource(alive));
  const outcomes = {};
  for (const key of keys) outcomes[key] = key in failures ? { fail: truncate(failures[key]) } : "ok";
  const runner = alive.length > 0 ? [process.execPath, join(batchDir, "runner.js")] : [];
  writeAll(1, JSON.stringify({ outcomes, runner }) + "\n");
}

build();
process.exit(0);
