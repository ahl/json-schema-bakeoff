//! ajv generator for the bakeoff harness.
//!
//!   version                  → "ajv <version>"
//!   generate <out_dir>       → stdin: JSON array of {key, draft, schema};
//!                              writes <out_dir>/<key>.js;
//!                              stdout: JSON array of {key, status, message?}
//!
//! One long-lived process handles every group in a draft.
//!
//! ajv is a validator, not a code generator, so the "generated code" for a
//! group is a small CommonJS module that embeds that group's schema and
//! compiles it with the Ajv class for the group's draft. The module is the
//! unit the harness builds and runs, so the contract is unchanged; see
//! README.md for what the row means.
//!
//! The status of a group is decided here rather than at build time: this
//! process has ajv in it, so it compiles each schema as soon as it has
//! written the module and reports a schema ajv refuses as `error`. The
//! module keeps its own lazy compile as a guard.

import { ensureDeps, depVersion, quietStdout, writeAll, HERE, NODE_MODULES } from "./deps.mjs";
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [, , cmd, outDir] = process.argv;

ensureDeps();

if (cmd === "version") {
  // writeAll, not process.stdout.write: stdout is a pipe here and
  // `process.exit` would truncate the asynchronous write.
  writeAll(1, `ajv ${depVersion("ajv")}\n`);
  process.exit(0);
}
if (cmd !== "generate" || !outDir) {
  process.stderr.write("usage: generate.mjs (version | generate <out_dir>)\n");
  process.exit(2);
}

// From here on stdout is the status array and nothing else.
quietStdout();

const root = process.env.BAKEOFF_ROOT;
if (!root) throw new Error("BAKEOFF_ROOT is not set");
const remotesDir = join(root, "suite", "remotes");

/** The runtime half of a module, embedded verbatim. */
const RUNTIME = readFileSync(join(HERE, "runtime.inc.js"), "utf8");

// ---------------------------------------------------------------- numbers

/** A number kept as the text it arrived as, not as a float64. */
class RawNumber {
  constructor(text) {
    this.text = text;
  }
}

/**
 * JSON.parse that keeps every number's source text.
 *
 * The harness serializes the suite's numbers with their original digits
 * (serde_json's `arbitrary_precision`), so `1e308`, `0.0001` and a
 * 50-digit integer arrive exactly as the suite wrote them. Parsing them
 * into JavaScript numbers here and stringifying them back would rewrite
 * the *schema* — `multipleOf: 1e-8` turns into `1e-8` harmlessly, but an
 * integer past 2^53 comes back as a different literal — so numbers are
 * held as text from the moment they are read until they are written into
 * the module.
 */
function parseKeepingNumbers(text) {
  return JSON.parse(text, function (_key, value, context) {
    if (typeof value === "number" && context && typeof context.source === "string") {
      return new RawNumber(context.source);
    }
    return value;
  });
}

// The reviver's third argument arrived in Node 21. Without it the fallback
// above silently rewrites every number in every schema through a float64,
// which is the one thing this generator promises not to do — so check once,
// here, rather than discovering it in a bignum result.
if (!(parseKeepingNumbers("[1e308]")[0] instanceof RawNumber)) {
  process.stderr.write(`ajv: this Node (${process.version}) has no JSON.parse source-text reviver; need Node 21+\n`);
  process.exit(1);
}

/** JSON.stringify, but numbers come back out exactly as they went in. */
function rawStringify(value) {
  if (value instanceof RawNumber) return value.text;
  if (value === null) return "null";
  if (Array.isArray(value)) return `[${value.map(rawStringify).join(",")}]`;
  if (typeof value === "object") {
    const parts = [];
    for (const key of Object.keys(value)) parts.push(`${JSON.stringify(key)}:${rawStringify(value[key])}`);
    return `{${parts.join(",")}}`;
  }
  return JSON.stringify(value);
}

// ---------------------------------------------------------------- modules

/**
 * The module for one group: four constants and the shared runtime.
 *
 * Absolute paths are baked in because the module is written under
 * `target/` and read back from a batch directory elsewhere, neither of
 * which can resolve `ajv` or find `suite/remotes/` on its own.
 */
function moduleSource(draft, schemaText) {
  return `// Generated by the bakeoff harness for ajv. Do not edit.
// See generators/ajv/README.md and generators/ajv/runtime.inc.js.
"use strict";

/** Where \`ajv\` and \`ajv-draft-04\` are installed. */
const AJV_MODULES = ${JSON.stringify(NODE_MODULES)};

/** The suite's \`http://localhost:1234/\` remotes, on local disk. */
const REMOTES_DIR = ${JSON.stringify(remotesDir)};

/** The suite directory this group came from; it picks the dialect. */
const DRAFT = ${JSON.stringify(draft)};

/**
 * The group's schema, as the text the harness sent. Embedded as text and
 * parsed at compile time so that no number in the schema round-trips
 * through a JavaScript float on the way in.
 */
const SCHEMA_TEXT = ${JSON.stringify(schemaText)};

${RUNTIME}`;
}

/** Not this group's verdict — the environment is broken. Die loudly. */
function fatal(what, e) {
  const message = e instanceof Error ? `${e.name}: ${e.message}` : String(e);
  process.stderr.write(`ajv: ${what}: ${message}\n`);
  process.exit(1);
}

/**
 * Error codes that can never be ajv's opinion of a schema: a file or
 * package that isn't there, or isn't readable. Bucketing one of these as a
 * `generation_error` would blame the tool for the harness's problem — and,
 * since every module reads the same files, would do it a thousand times
 * over and leave the result committable. So they are fatal.
 */
const ENVIRONMENT_CODES = new Set(["ENOENT", "ENOTDIR", "EACCES", "EPERM", "EISDIR", "MODULE_NOT_FOUND"]);

/**
 * Buckets an exception from ajv, or dies if it isn't ajv's.
 *
 * ajv reports everything it can't do by throwing: a `MissingRefError` for
 * an unresolvable `$ref`, a plain `Error` for a schema its meta-schema
 * rejects or a `$schema` it doesn't know. Those are generation *errors* —
 * the tool said no. A `RangeError` is a blown stack, which is a crash
 * wearing an error's clothes, so it is a panic. A `SyntaxError` stays an
 * error: ajv builds the validator by `new Function`, so a syntax error is
 * ajv's codegen failing on this schema, which is a real result.
 */
function classify(key, e) {
  if (e && ENVIRONMENT_CODES.has(e.code)) fatal(`${key}: environment error, not a schema verdict`, e);
  const message = e instanceof Error ? `${e.name}: ${e.message}` : String(e);
  return { status: e instanceof RangeError ? "panic" : "error", message };
}

/** Node keys the require cache by realpath, so resolve before deleting. */
function uncache(require_, path) {
  try {
    delete require_.cache[require_.resolve(path)];
  } catch {
    // Never required, or already gone. Either way there's nothing to drop.
  }
}

/**
 * Prove the environment works before judging a single schema.
 *
 * A module that can't find `ajv`, or a `suite/remotes/` that isn't there
 * (an unchecked-out submodule, a wrong `BAKEOFF_ROOT`), would otherwise
 * throw inside every group's compile and be recorded as a thousand
 * `generation_error`s against ajv. So compile the most trivial schema
 * there is through exactly the same code path first: if that fails,
 * nothing about the run is meaningful. It also warms the process-wide
 * remotes cache the real modules share.
 */
function preflight(require_, draft) {
  const path = join(outDir, "__preflight.js");
  try {
    writeFileSync(path, moduleSource(draft, "true"));
    require_(path).__conformanceCompile();
  } catch (e) {
    fatal(`preflight failed for ${draft} (is suite/remotes/ present? is ajv installed?)`, e);
  } finally {
    uncache(require_, path);
  }
}

async function main() {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  const groups = parseKeepingNumbers(Buffer.concat(chunks).toString("utf8"));
  if (groups.length === 0) {
    writeAll(1, "[]\n");
    return;
  }

  mkdirSync(outDir, { recursive: true });
  // The generated modules are CommonJS; nothing above target/ says so.
  writeFileSync(join(outDir, "package.json"), '{ "type": "commonjs" }\n');

  const require_ = createRequire(join(outDir, "noop.cjs"));
  preflight(require_, groups[0].draft);

  const statuses = [];
  for (const group of groups) {
    const key = group.key;
    const path = join(outDir, `${key}.js`);
    try {
      // Writing the module is inside the try as well: a failure here is
      // not a verdict on the schema, and `classify` sends it to `fatal`
      // rather than letting a dead process take the draft's whole status
      // array with it.
      writeFileSync(path, moduleSource(group.draft, rawStringify(group.schema)));
      // Compiling here is what decides the status, and it also proves the
      // module loads. Dropping it from the require cache afterwards keeps
      // a draft's worth of compiled validators from piling up in memory.
      require_(path).__conformanceCompile();
      statuses.push({ key, status: "ok" });
    } catch (e) {
      statuses.push({ key, ...classify(key, e) });
    } finally {
      uncache(require_, path);
    }
  }
  writeAll(1, JSON.stringify(statuses) + "\n");
}

await main();
process.exit(0);
