//! json-schema-to-zod generator for the bakeoff harness.
//!
//!   version              → "json-schema-to-zod <version> + zod <version>"
//!   generate <out_dir>   → stdin: JSON array of {key, draft, schema};
//!                          writes <out_dir>/<key>.ts;
//!                          stdout: JSON array of {key, status, message?}
//!
//! One long-lived process handles every group.
//!
//! The tool is a source-to-source converter: `jsonSchemaToZod(schema)`
//! returns a *string* of JavaScript — a single zod expression such as
//! `z.object({ "a": z.string() })`. There is no type to name, so the
//! contract's "call the root type `Root`" doesn't apply; the expression is
//! bound to a module-local `schema` and wrapped in the entry point the
//! runner calls.
//!
//! Two things the tool has no setting for, and which therefore can't be
//! passed through:
//!
//! - **Dialect.** `Options` has no draft/dialect field, and `$schema` is
//!   ignored outright (it isn't in the keyword table). `draft` is read off
//!   stdin and dropped. The 2019-09 and 2020-12 relocations — `items` →
//!   `prefixItems`, `dependencies` → `dependentRequired` — are simply
//!   unknown keywords there, and draft 4's boolean `exclusiveMinimum` is
//!   handled because the *number* parser looks for it explicitly.
//! - **References.** There is no `$ref` resolver and no fetcher. `$ref` is
//!   not a keyword the dispatcher knows, so a schema whose root is a
//!   `$ref` falls through to `z.any()` — including the suite's
//!   `http://localhost:1234/...` remotes. Nothing is ever fetched; the
//!   `z.any()` that comes back is recorded like any other output.
//!
//! Everything else is the tool's own default: `module: "none"` (just the
//! expression), `zodVersion` defaults to 4, and `withoutDefaults` /
//! `withoutDescribes` / `depth` are left alone so the measurement is of
//! the tool as it ships.

import { ensureDeps, depVersion, quietStdout, writeAll } from "./deps.mjs";

const [, , cmd, outDir] = process.argv;

ensureDeps();

if (cmd === "version") {
  // writeAll, not process.stdout.write: stdout is a pipe here and
  // `process.exit` would truncate the asynchronous write.
  writeAll(1, `json-schema-to-zod ${depVersion("json-schema-to-zod")} + zod ${depVersion("zod")}\n`);
  process.exit(0);
}
if (cmd !== "generate" || !outDir) {
  process.stderr.write("usage: generate.mjs (version | generate <out_dir>)\n");
  process.exit(2);
}

// From here on stdout is the status array and nothing else.
quietStdout();

const { mkdirSync, writeFileSync } = await import("node:fs");
const { join } = await import("node:path");
const { jsonSchemaToZod } = await import("json-schema-to-zod");

/** How long one schema gets before we call it a hang. */
const TIMEOUT_MS = 30_000;

/**
 * The module we emit for one group.
 *
 * TypeScript, not JavaScript, and run by node's own type stripping rather
 * than compiled — see build.mjs for why. The `.ts` extension on the import
 * specifier is required by node's ESM resolver.
 *
 * `JSON.parse` lives inside the module so the runner can hand over the
 * suite's digits as text; what JS's parser then does with a 50-digit
 * integer is the tool's user's experience, not the harness's.
 */
function module_(expr) {
  return `// Generated by the bakeoff harness from json-schema-to-zod output.
import { z } from "zod";

const schema = ${expr};

export function __conformanceCheck(json: string): void {
  schema.parse(JSON.parse(json));
}
`;
}

/**
 * Buckets an exception.
 *
 * json-schema-to-zod has no error type of its own: it either returns a
 * string or throws from inside a parser. A `TypeError` from a parser
 * reading a keyword it didn't expect (`{"enum": 3}`, say) is the tool
 * saying "I can't do this", so it's a generation *error*. The two ways it
 * can instead be said to have crashed are a `RangeError` — stack
 * exhausted, on a schema nested deeper than its recursive descent likes —
 * and the timeout below. (There is no third kind: a thrown "internal
 * error" string isn't a thing in this package, and a real process-level
 * crash would take this process with it and never reach `classify`.)
 */
function classify(e) {
  const message = e instanceof Error ? `${e.name}: ${e.message}` : String(e);
  if (e instanceof RangeError || /timed out after/.test(message)) {
    return { status: "panic", message };
  }
  return { status: "error", message };
}

function timeout(ms) {
  let timer;
  const promise = new Promise((_resolve, reject) => {
    timer = setTimeout(() => reject(new Error(`timed out after ${ms}ms`)), ms);
  });
  return { promise, cancel: () => clearTimeout(timer) };
}

async function main() {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  const groups = JSON.parse(Buffer.concat(chunks).toString("utf8"));

  mkdirSync(outDir, { recursive: true });
  const statuses = [];
  for (const { key, schema } of groups) {
    const guard = timeout(TIMEOUT_MS);
    // The tool is synchronous, so the timeout can only fire if it returns
    // — a hang inside it blocks the event loop and the harness's own
    // generate timeout is what saves us. Race anyway: it costs nothing and
    // it covers a future version that awaits something.
    const work = (async () => jsonSchemaToZod(schema))().then(
      (expr) => ({ expr }),
      (error) => ({ error }),
    );
    let expr;
    try {
      const done = await Promise.race([work, guard.promise]);
      if ("error" in done) throw done.error;
      if (typeof done.expr !== "string" || done.expr.trim() === "") {
        throw new Error(`the tool returned ${typeof done.expr}, not an expression`);
      }
      expr = done.expr;
    } catch (e) {
      statuses.push({ key, ...classify(e) });
      continue;
    } finally {
      guard.cancel();
    }
    // Writing the module is ours, not the tool's: a failure here is a
    // broken run, not a schema json-schema-to-zod couldn't handle.
    writeFileSync(join(outDir, `${key}.ts`), module_(expr));
    statuses.push({ key, status: "ok" });
  }
  // stdout may be a pipe, where `write` is asynchronous and a process that
  // exits first truncates it.
  writeAll(1, JSON.stringify(statuses) + "\n");
}

await main();
// The status array is out, so we're done — but a generation we gave up on
// may still hold a timer, and node won't exit while it does.
process.exit(0);
