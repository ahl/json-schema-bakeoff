//! `build.mjs <gen_dir> <batch_dir>`: the build step of the generator
//! contract.
//!
//! Reads a JSON array of module keys on stdin, assembles them into one
//! runner, attributes load failures back to keys, drops the failures, and
//! prints `{"outcomes": {key: "ok" | {"fail": diagnostic}}, "runner": [exe, ...]}`
//! on stdout. Everything else goes to stderr.
//!
//! ## There is no compiler
//!
//! json-schema-to-zod emits a zod expression, which is JavaScript with a
//! sprinkling of TypeScript: `parseOneOf` writes an explicit type argument
//! (`schemas.reduce<{ errors: z.core.$ZodIssue[]; failed: number }>(...)`)
//! that plain JS can't parse. All of it is *erasable* TypeScript, though —
//! annotations and type arguments, no enums, no namespaces, no parameter
//! properties — so node runs the emitted `.ts` files directly with its own
//! type stripping. No `tsc`, and so no `typescript` dependency.
//!
//! That is also the honest measurement. Running the output through `tsc`
//! would add a type check the tool never promised to pass (its README says
//! the output "is not meant to be used at runtime"), and type errors would
//! land in `compile_fail` next to real breakage. What we want to know is
//! whether the emitted source *runs*, so the build step is a load probe:
//! import each module once, by itself, and keep the ones that import
//! cleanly. Two things fail there and both are `compile_fail` in the
//! bakeoff's sense — the tool wrote source that doesn't parse, or zod
//! refused to build the schema the tool asked for (`z.string().ip()`, say,
//! which zod 4 removed).
//!
//! Probing in a child process, one key at a time, and restarting past
//! whatever index never reported is how a module that takes the whole
//! process down (stack exhaustion inside zod on a deeply nested schema)
//! gets blamed on itself rather than on its neighbours. It is the same
//! shape as the harness's own runner loop, including the `ready` line that
//! separates "this module killed the probe" from "the probe never ran".
//! A canary module goes first for the same reason: a failure that would
//! hit every module equally (no `zod`, no type stripping) is ours to fail
//! on, not a few thousand `compile_fail`s.

import { ensureDeps, quietStdout, writeAll, HERE } from "./deps.mjs";
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** Cap on stored diagnostic text per module; these end up in results.json. */
const MAX_DIAG_LEN = 4000;

/**
 * How long a probe process gets, as a function of how many modules it
 * still has to import.
 *
 * `spawnSync` can only bound the whole process, not the gap between two
 * lines, so the cap has to cover a whole draft's worth of imports — 1,000
 * of them in 2020-12. Importing one is milliseconds (zod itself is loaded
 * once and cached), so this is roughly two orders of magnitude of slack: a
 * loaded machine must not turn into a spurious `compile_fail`, which is
 * what a flat cap would do the moment the batch outgrew it.
 */
const PROBE_BASE_MS = 60_000;
const PROBE_PER_MODULE_MS = 250;

/** How long the canary module gets to prove the batch dir works. */
const CANARY_TIMEOUT_MS = 60_000;

/** How much of a dead probe's stderr to keep. */
const STDERR_TAIL = 800;

const [, , genDir, batchDir] = process.argv;
if (!genDir || !batchDir) {
  process.stderr.write("usage: build.mjs <gen_dir> <batch_dir>\n");
  process.exit(2);
}

const chunks = [];
for await (const chunk of process.stdin) chunks.push(chunk);
const keys = JSON.parse(Buffer.concat(chunks).toString("utf8"));

// stdout is the protocol from here on.
quietStdout();
ensureDeps();

function truncate(s, max = MAX_DIAG_LEN) {
  return s.length <= max ? s : `${s.slice(0, max)}\n... (truncated)`;
}

function tail(s, max = STDERR_TAIL) {
  const t = s.trim();
  return t.length <= max ? t : `...${t.slice(t.length - max)}`;
}

/**
 * The runner, as the protocol in DESIGN.md defines it.
 *
 * TypeScript only so that the `.ts` import specifiers and the emitted
 * modules sit in one language; nothing here is type-checked.
 *
 * Numbers come in through `JSON.parse`'s reviver `source`, which hands
 * over the literal text the suite wrote, and go back out through
 * `rawStringify`, so `__conformanceCheck` receives the original digits and
 * does its own `JSON.parse`. Where precision stops is then JavaScript's
 * business — a 50-digit integer becomes a float64 inside the module, which
 * is exactly what a user of this tool would get.
 */
function runnerSource(alive) {
  const imports = alive.map((k) => `import * as ${k} from "./${k}.ts";`).join("\n");
  const table = alive.map((k) => `  "${k}": ${k}.__conformanceCheck,`).join("\n");
  return `// Generated by the bakeoff harness. See DESIGN.md for the runner protocol.
import { readFileSync, writeSync } from "node:fs";

${imports}

type Check = (json: string) => void;

const MODULES: { [key: string]: Check } = {
${table}
};

/** A number kept as the text the suite wrote, not as a float64. */
class RawNumber {
  text: string;
  constructor(text: string) {
    this.text = text;
  }
}

function parseCases(text: string): any[] {
  const reviver = function (_key: string, value: any, context?: any): any {
    if (typeof value === "number" && context && typeof context.source === "string") {
      return new RawNumber(context.source);
    }
    return value;
  };
  return JSON.parse(text, reviver as any);
}

/** JSON.stringify, but numbers come back out exactly as they went in. */
function rawStringify(value: any): string {
  if (value instanceof RawNumber) return value.text;
  if (value === null) return "null";
  if (Array.isArray(value)) return "[" + value.map(rawStringify).join(",") + "]";
  if (typeof value === "object") {
    const parts: string[] = [];
    for (const key of Object.keys(value)) {
      parts.push(JSON.stringify(key) + ":" + rawStringify(value[key]));
    }
    return "{" + parts.join(",") + "}";
  }
  return JSON.stringify(value);
}

/**
 * A rejection as one line.
 *
 * A \`ZodError\`'s \`message\` is the whole issue list pretty-printed as
 * JSON, which would put kilobytes per case into results.json. Keep the
 * first few issues with their paths instead.
 */
function describe(e: any): string {
  let text: string;
  if (e && Array.isArray(e.issues)) {
    const shown = e.issues.slice(0, 3).map((i: any) => {
      const path = Array.isArray(i.path) && i.path.length ? i.path.join(".") : "<root>";
      return path + ": " + i.message;
    });
    const more = e.issues.length > 3 ? " (+" + (e.issues.length - 3) + " more)" : "";
    text = "ZodError: " + shown.join("; ") + more;
  } else {
    text = e && e.message ? String(e.message) : String(e);
  }
  return text.length > 1000 ? text.slice(0, 1000) + "..." : text;
}

function emit(value: any): void {
  // stdout is a pipe, where process.stdout.write is asynchronous and the
  // harness may be waiting on this very line. writeSync on a pipe can
  // stop short (and raise EAGAIN once the pipe is full), so loop: half a
  // line of JSON is a line the harness can't parse.
  const buf = Buffer.from(JSON.stringify(value) + "\\n", "utf8");
  let off = 0;
  while (off < buf.length) {
    try {
      off += writeSync(1, buf, off, buf.length - off);
    } catch (e: any) {
      if (!e || e.code !== "EAGAIN") throw e;
    }
  }
}

function main(): void {
  const argv: string[] = process.argv;
  if (argv.length !== 4) {
    writeSync(2, "usage: runner <cases.json> <start-index>\\n");
    process.exit(2);
  }
  const cases = parseCases(readFileSync(argv[2], "utf8"));
  const start = Number.parseInt(argv[3], 10);

  emit({ ready: start });
  for (let i = start; i < cases.length; i++) {
    const key: string = cases[i].key;
    const check = MODULES[key];
    let outcome: any;
    if (check === undefined) {
      outcome = { panic: "module not compiled" };
    } else {
      try {
        check(rawStringify(cases[i].data));
        outcome = "accept";
      } catch (e: any) {
        // Nothing zod throws is distinguishable from an ordinary
        // mismatch, so everything caught here is a reject; only a dead
        // process counts as a panic, and that one the harness sees for
        // itself.
        outcome = { reject: describe(e) };
      }
    }
    emit({ case: { i: i, r: outcome } });
  }
}

main();
`;
}

/**
 * Stage the batch: the emitted modules, a `"type": "module"` marker so
 * node treats the `.ts` files as ESM, and a `zod` symlink so `import { z }
 * from "zod"` resolves from a directory under `target/` that has no
 * install of its own.
 */
function stage() {
  rmSync(batchDir, { recursive: true, force: true });
  mkdirSync(join(batchDir, "node_modules"), { recursive: true });
  writeFileSync(join(batchDir, "package.json"), '{ "type": "module" }\n');
  symlinkSync(join(HERE, "node_modules", "zod"), join(batchDir, "node_modules", "zod"), "dir");
  for (const key of keys) {
    writeFileSync(join(batchDir, `${key}.ts`), readFileSync(join(genDir, `${key}.ts`)));
  }
  writeFileSync(join(batchDir, "keys.json"), JSON.stringify(keys));
}

/**
 * Prove that the batch directory can run a module at all, before blaming
 * any of the tool's output for not loading.
 *
 * Every module starts with `import { z } from "zod"`, so a broken install,
 * a missing symlink or a node without type stripping fails all of them
 * identically — and a per-module probe would dutifully record a few
 * thousand `compile_fail`s that say nothing about the tool. An error we
 * can't attribute to a module has to be a hard failure instead.
 */
function canary() {
  const path = join(batchDir, "__canary.ts");
  writeFileSync(
    path,
    `// Written by build.mjs: proof that this directory can run a module.
import { z } from "zod";
const ok: boolean = z.string().safeParse("x").success;
if (!ok) throw new Error("zod parsed a string wrong");
`,
  );
  const out = spawnSync(process.execPath, [path], { cwd: batchDir, encoding: "utf8", timeout: CANARY_TIMEOUT_MS });
  if (out.error) throw out.error;
  if (out.status !== 0) {
    throw new Error(
      `${path} does not run (status ${out.status}, signal ${out.signal}), so no generated module in this ` +
        `directory could either: that's a broken install, symlink or node, not a bad schema.\n${tail(out.stderr ?? "", 4000)}`,
    );
  }
}

/**
 * Import every module once and return `{key: diagnostic}` for the ones
 * that don't load.
 *
 * The probe reports an absolute index per module and flushes, so a key
 * that never reports is the one that killed the process; restart past it.
 * A probe that doesn't even print `ready` never reached its first import,
 * so there is nothing to blame a module for — that one is ours.
 */
function probe() {
  const failures = {};
  let next = 0;
  while (next < keys.length) {
    const limit = PROBE_BASE_MS + (keys.length - next) * PROBE_PER_MODULE_MS;
    const out = spawnSync(process.execPath, [join(HERE, "probe.mjs"), batchDir, String(next)], {
      cwd: batchDir,
      encoding: "utf8",
      timeout: limit,
      maxBuffer: 256 * 1024 * 1024,
    });
    // `spawnSync` reports a timeout as an `ETIMEDOUT` error plus the signal
    // it killed the child with; a module that aborts dies by signal too, so
    // the error is the only thing that tells the two apart.
    const timedOut = out.error?.code === "ETIMEDOUT";
    if (out.error && !timedOut) throw out.error;

    let ready = false;
    let last = next - 1;
    for (const line of (out.stdout ?? "").split("\n")) {
      if (!line.trim()) continue;
      let rec;
      try {
        rec = JSON.parse(line);
      } catch {
        continue;
      }
      if (rec.ready === next) ready = true;
      if (typeof rec.i !== "number" || rec.i < next || rec.i >= keys.length) continue;
      if (rec.r !== "ok") failures[keys[rec.i]] = truncate(String(rec.r.fail ?? "load failed"));
      if (rec.i > last) last = rec.i;
    }
    if (!ready) {
      throw new Error(
        `probe.mjs never started on ${batchDir} from index ${next} ` +
          `(${timedOut ? `no output within ${limit}ms` : `status ${out.status}, signal ${out.signal}`}): ` +
          `that's the probe, not a module.\n${tail(out.stderr ?? "", 4000)}`,
      );
    }

    if (last >= keys.length - 1) break;
    // Whatever comes after the last module that reported is the one that
    // took the process down.
    const dead = last + 1;
    const how = timedOut
      ? `no progress within ${limit}ms`
      : out.signal
        ? `killed by ${out.signal}`
        : `exit status ${out.status}`;
    failures[keys[dead]] = truncate(`loading this module killed the probe process (${how}); stderr: ${tail(out.stderr ?? "")}`);
    process.stderr.write(`json-schema-to-zod: probe died on ${keys[dead]} (${how}), restarting\n`);
    next = dead + 1;
  }
  return failures;
}

stage();
canary();
const failures = probe();
const alive = keys.filter((k) => !(k in failures));
process.stderr.write(`json-schema-to-zod: ${alive.length} of ${keys.length} module(s) load\n`);

const runnerPath = join(batchDir, "runner.ts");
writeFileSync(runnerPath, runnerSource(alive));

const outcomes = {};
for (const key of keys) {
  outcomes[key] = key in failures ? { fail: failures[key] } : "ok";
}
writeAll(1, JSON.stringify({ outcomes, runner: alive.length ? [process.execPath, runnerPath] : [] }) + "\n");
