//! Feed a schema to schemafy and capture code, error, or panic.

use quote::ToTokens;
use schemafy_lib::{Expander, Schema};
use std::sync::Mutex;
use std::time::Duration;

/// Identity string: `schemafy <pinned schemafy_lib version>` (from build.rs).
pub const VERSION: &str = concat!("schemafy ", env!("SCHEMAFY_CRATE_VERSION"));

/// What `schemafy_lib` tells generated code to call its runtime support
/// crate; the default, and what `batch-deps.toml` pins.
const SCHEMAFY_PATH: &str = "::schemafy_core::";

#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub enum GenOutcome {
    /// Generated Rust source. `root` is the type path to deserialize into;
    /// it refers to items in `code`, which is a complete module body
    /// (items only).
    Code { code: String, root: String },
    Error(String),
    Panic(String),
    /// The generation thread was still running at the timeout and has been
    /// abandoned. Reported to the harness as a panic like any other, but
    /// the caller has to know, because the process is no longer fit to
    /// generate anything else (see below).
    Timeout(String),
}

/// Run schemafy on a schema with a root type name of `Root`.
///
/// Runs on a dedicated thread with a large stack (schemafy resolves `$ref`
/// and `allOf` by recursion) and catches panics. A generation that exceeds
/// `timeout` is abandoned and reported as `Timeout`.
///
/// An abandoned thread keeps running, and it holds both `HOOK_LOCK` and the
/// process-global panic hook, so the *next* call would block on the lock
/// until it finished — and if it finishes by overflowing the stack it
/// aborts the process under whatever group is current by then. A timeout is
/// therefore terminal for the process: the caller must report it and exit,
/// and let its supervisor continue in a fresh one.
pub fn generate(schema: &serde_json::Value, timeout: Duration) -> GenOutcome {
    let schema_value = schema.clone();
    let (tx, rx) = std::sync::mpsc::channel();
    std::thread::Builder::new()
        .name("generate".to_string())
        .stack_size(256 * 1024 * 1024)
        .spawn(move || {
            let _ = tx.send(generate_inner(schema_value));
        })
        .expect("spawn generation thread");
    match rx.recv_timeout(timeout) {
        Ok(outcome) => outcome,
        Err(_) => GenOutcome::Timeout(format!("generation did not finish within {timeout:?}")),
    }
}

fn generate_inner(schema_value: serde_json::Value) -> GenOutcome {
    // schemafy's whole input type is `schemafy_lib::Schema`, a draft-4
    // meta-schema struct generated by schemafy itself. There is no
    // boolean-schema case and no number-valued `exclusiveMaximum`, so
    // anything the struct can't hold stops here. Unknown keywords (`const`,
    // `$defs`, `if`/`then`/`else`, ...) are simply dropped, which is why so
    // much of the suite generates but over-accepts.
    let schema: Schema = match serde_json::from_value(schema_value) {
        Ok(s) => s,
        Err(e) => {
            return GenOutcome::Error(format!(
                "schema did not parse as schemafy_lib::Schema: {e}"
            ));
        }
    };

    // Capture the panic message without letting the default hook spew to
    // stderr. The hook is process-global, so serialize generation across
    // threads while it is installed.
    static HOOK_LOCK: Mutex<()> = Mutex::new(());
    let _guard = HOOK_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let captured: std::sync::Arc<Mutex<Option<String>>> = Default::default();
    let prev = std::panic::take_hook();
    {
        let captured = captured.clone();
        std::panic::set_hook(Box::new(move |info| {
            let msg = info
                .payload()
                .downcast_ref::<String>()
                .cloned()
                .or_else(|| info.payload().downcast_ref::<&str>().map(|s| s.to_string()))
                .unwrap_or_else(|| "non-string panic payload".to_string());
            let loc = info.location().map(|l| format!(" at {}:{}", l.file(), l.line())).unwrap_or_default();
            *captured.lock().unwrap() = Some(format!("{msg}{loc}"));
        }));
    }
    // `Expander::expand` is infallible in signature: schemafy reports every
    // problem (a `$ref` with no definition, a non-string `enum`, a name
    // that isn't a Rust identifier) by panicking. So `error` here means
    // only "the schema didn't fit `Schema`", and everything else is a
    // panic.
    let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        let mut expander = Expander::new(Some(ROOT_NAME), SCHEMAFY_PATH, &schema);
        expander.expand(&schema)
    }));
    std::panic::set_hook(prev);

    match result {
        Ok(stream) => match syn::parse2::<syn::File>(stream.clone()) {
            Ok(file) => {
                let (file, root) = prepare(file);
                GenOutcome::Code { code: prettyplease::unparse(&file), root }
            }
            // Unparseable output still gets handed to rustc so the failure
            // lands in compile_fail with a real diagnostic.
            Err(_) => GenOutcome::Code { code: stream.to_string(), root: ROOT_NAME.to_string() },
        },
        Err(_) => {
            let msg = captured.lock().unwrap().take().unwrap_or_else(|| "unknown panic".to_string());
            GenOutcome::Panic(msg)
        }
    }
}

/// The root name handed to `Expander::new`. schemafy names the root type
/// after it verbatim (it is already PascalCase), whether that comes out as
/// a struct, an enum, or a `pub type Root = ...` alias.
const ROOT_NAME: &str = "Root";

/// Make schemafy's output usable as a module inside the batch crate, and
/// report the root type to deserialize into.
///
/// Two fixups:
///
/// * Inner attributes (`#![...]`) and `extern crate` items are legal at a
///   crate root but not inside a non-root module, so they're dropped.
///   schemafy 0.6 emits neither; this is belt-and-braces against a change.
/// * schemafy's output names `Deserialize`/`Serialize` (and, for an
///   integer `enum` with `enumNames`, `Deserialize_repr`/`Serialize_repr`)
///   unqualified, exactly as its own crate does with `#[macro_use] extern
///   crate serde_derive`. A caller is expected to have imported them, so we
///   do, the way schemafy's own doc example does.
fn prepare(mut file: syn::File) -> (syn::File, String) {
    file.attrs.clear();
    file.items.retain(|item| !matches!(item, syn::Item::ExternCrate(_)));
    let needs_repr = file.items.iter().any(|item| {
        matches!(item, syn::Item::Enum(e) if e.attrs.iter().any(|a| {
            a.to_token_stream().to_string().contains("Deserialize_repr")
        }))
    });

    // Does an item actually define `Root`? schemafy drops the root entirely
    // when the alias would be self-referential (a root of `{"$ref": "#"}`
    // resolves to the root name, and `pub type Root = Root;` is skipped),
    // so the module can come out with no root type at all. Say so in a
    // comment and still reference `Root`: rustc's "cannot find type `Root`"
    // is the honest outcome, and it lands in compile_fail.
    let defines_root = file.items.iter().any(|item| match item {
        syn::Item::Struct(i) => i.ident == ROOT_NAME,
        syn::Item::Enum(i) => i.ident == ROOT_NAME,
        syn::Item::Type(i) => i.ident == ROOT_NAME,
        _ => false,
    });

    let prelude: syn::File = if needs_repr {
        syn::parse_quote! {
            use ::serde::{Deserialize, Serialize};
            use ::serde_repr::{Deserialize_repr, Serialize_repr};
        }
    } else {
        syn::parse_quote! {
            #[allow(unused_imports)]
            use ::serde::{Deserialize, Serialize};
        }
    };
    let mut items = prelude.items;
    if !defines_root {
        items.push(syn::parse_quote! {
            /// schemafy emitted no type named `Root` for this schema.
            #[allow(dead_code)]
            const __SCHEMAFY_NO_ROOT: () = ();
        });
    }
    items.append(&mut file.items);
    file.items = items;
    (file, ROOT_NAME.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    const T: Duration = Duration::from_secs(10);

    #[test]
    fn struct_root() {
        match generate(&serde_json::json!({"properties": {"a": {"type": "string"}}}), T) {
            GenOutcome::Code { root, code } => {
                assert_eq!(root, "Root");
                assert!(code.contains("pub struct Root"), "{code}");
            }
            other => panic!("{other:?}"),
        }
    }

    #[test]
    fn alias_root() {
        // No properties and no `enum`: schemafy emits an alias, not a struct.
        match generate(&serde_json::json!({"type": "integer"}), T) {
            GenOutcome::Code { root, code } => {
                assert_eq!(root, "Root");
                assert!(code.contains("pub type Root = i64"), "{code}");
            }
            other => panic!("{other:?}"),
        }
    }

    #[test]
    fn integer_enum_pulls_in_serde_repr() {
        // `enumNames` is schemafy's own extension; with numeric values it
        // reaches for serde_repr, which `batch-deps.toml` pins.
        match generate(&serde_json::json!({"enum": [1, 2], "enumNames": ["A", "B"]}), T) {
            GenOutcome::Code { code, .. } => {
                assert!(code.contains("use ::serde_repr::"), "{code}");
                assert!(code.contains("Deserialize_repr"), "{code}");
            }
            other => panic!("{other:?}"),
        }
    }

    #[test]
    fn self_referential_root_defines_nothing() {
        // `$ref: "#"` resolves to the root's own name, and schemafy skips
        // `pub type Root = Root;`, so the module has no root type at all.
        match generate(&serde_json::json!({"$ref": "#"}), T) {
            GenOutcome::Code { code, root } => {
                assert_eq!(root, "Root");
                assert!(code.contains("__SCHEMAFY_NO_ROOT"), "{code}");
            }
            other => panic!("{other:?}"),
        }
    }

    #[test]
    fn a_generation_that_runs_out_of_time_is_a_timeout() {
        // Zero patience, so this doesn't depend on finding a slow schema.
        // `Timeout` rather than `Panic` is what tells the worker to quit.
        assert!(matches!(
            generate(&serde_json::json!({"type": "integer"}), Duration::ZERO),
            GenOutcome::Timeout(_)
        ));
    }

    #[test]
    fn boolean_schema_is_an_error() {
        assert!(matches!(generate(&serde_json::json!(true), T), GenOutcome::Error(_)));
    }

    #[test]
    fn missing_definition_is_a_panic() {
        // `allOf` merging resolves the `$ref`, and schemafy panics when it
        // can't find the definition.
        assert!(matches!(
            generate(&serde_json::json!({"allOf": [{"$ref": "#/definitions/nope"}]}), T),
            GenOutcome::Panic(_)
        ));
    }

    #[test]
    fn dangling_ref_in_a_property_names_a_type_that_does_not_exist() {
        // A `$ref` in a field position is turned into a type *name* without
        // being resolved, so this generates and then fails to compile.
        match generate(&serde_json::json!({"properties": {"a": {"$ref": "#/definitions/nope"}}}), T) {
            GenOutcome::Code { code, .. } => assert!(code.contains("Nope"), "{code}"),
            other => panic!("{other:?}"),
        }
    }
}
