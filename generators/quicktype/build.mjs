//! `build.mjs <target> <gen_dir> <batch_dir>`: the build step of the
//! generator contract, for all three quicktype targets.
//!
//! Reads a JSON array of module keys on stdin, compiles those modules
//! together, attributes compiler diagnostics back to keys, drops the
//! failures, repeats until clean, and prints
//! `{"outcomes": {key: "ok" | {"fail": diagnostic}}, "runner": [exe, ...]}`
//! on stdout. Everything else goes to stderr.
//!
//! - `rust` hands the whole job to `rust-batch`, the repo's shared Rust
//!   build step, and relays its answer verbatim.
//! - `go` builds a module whose every group is its own package, plus a
//!   `main.go` that imports the live ones.
//! - `typescript` compiles the modules and a `runner.ts` with `tsc`.
//!
//! The Go and TypeScript halves follow rust-batch's shape: a compiler only
//! reports so much before it gives up, so a single pass can't find every
//! broken module. Blame each diagnostic on a module by the file it names,
//! drop those modules, and compile again.

import { ensureDeps, quietStdout, writeAll, HERE } from "./deps.mjs";
import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

/** How many compile passes we'll spend shaking out broken modules. */
const MAX_PASSES = 10;

/** Cap on stored diagnostic text per module; these end up in results.json. */
const MAX_DIAG_LEN = 4000;

const [, , target, genDir, batchDir] = process.argv;
if (!target || !genDir || !batchDir) {
  process.stderr.write("usage: build.mjs <rust|go|typescript> <gen_dir> <batch_dir>\n");
  process.exit(2);
}

const chunks = [];
for await (const chunk of process.stdin) chunks.push(chunk);
const keys = JSON.parse(Buffer.concat(chunks).toString("utf8"));

// stdout is the protocol from here on.
quietStdout();
ensureDeps();

function emit(outcomes, runner) {
  writeAll(1, JSON.stringify({ outcomes, runner }) + "\n");
}

function truncate(s, max = MAX_DIAG_LEN) {
  return s.length <= max ? s : `${s.slice(0, max)}\n... (truncated)`;
}

/** `{key: "ok"}` for survivors, `{key: {fail}}` for the rest. */
function outcomesFor(all, failures) {
  const out = {};
  for (const key of all) {
    out[key] = key in failures ? { fail: truncate(failures[key]) } : "ok";
  }
  return out;
}

// ---------------------------------------------------------------- rust

/**
 * Rust modules are rust-batch's business: it owns the batch crate, the
 * shared target dir and the runner. Pass the keys through — the batch dir
 * is the crate dir, since rust-batch derives the runner's binary name from
 * that directory's absolute path and so keeps batches from uplifting over
 * each other's executable — and relay the result object unchanged.
 */
function buildRust() {
  const root = process.env.BAKEOFF_ROOT;
  if (!root) throw new Error("BAKEOFF_ROOT is not set");
  const cargo = process.env.CARGO ?? "cargo";
  const stdout = execFileSync(
    cargo,
    ["run", "-q", "--manifest-path", join(root, "Cargo.toml"), "-p", "rust-batch", "--", "build", genDir, batchDir],
    { input: JSON.stringify(keys), stdio: ["pipe", "pipe", "inherit"], maxBuffer: 256 * 1024 * 1024 },
  );
  writeAll(1, stdout);
}

// ------------------------------------------------------------------ go

const GO_MODULE = "bakeoff";

/** Environment for `go`: no workspace, no network, no module fetching. */
const goEnv = { ...process.env, GOWORK: "off", GOFLAGS: "-mod=mod", GOPROXY: "off", GO111MODULE: "on" };

function goMain(alive) {
  const imports = alive.map((k) => `\t${k} "${GO_MODULE}/${k}"`).join("\n");
  const table = alive.map((k) => `\t"${k}": ${k}.ConformanceCheck,`).join("\n");
  return `// Generated by the bakeoff harness. See DESIGN.md for the runner protocol.
package main

import (
\t"encoding/json"
\t"fmt"
\t"os"
\t"strconv"
${imports}
)

// A case's data stays as raw bytes so that \`json.Unmarshal\` sees the
// digits the suite wrote: decoding to interface{} and re-encoding would
// round every number through a float64.
type conformanceCase struct {
\tKey  string          \`json:"key"\`
\tData json.RawMessage \`json:"data"\`
}

var modules = map[string]func([]byte) error{
${table}
}

// Go has no exceptions for ordinary failures, so a returned error is a
// reject and only a recovered panic is a panic. A stack overflow is fatal
// and unrecoverable; the harness notices the dead process and restarts us
// past the offending case.
func runOne(check func([]byte) error, data []byte) (outcome any) {
\tdefer func() {
\t\tif r := recover(); r != nil {
\t\t\toutcome = map[string]string{"panic": fmt.Sprint(r)}
\t\t}
\t}()
\tif err := check(data); err != nil {
\t\treturn map[string]string{"reject": err.Error()}
\t}
\treturn "accept"
}

func main() {
\tif len(os.Args) != 3 {
\t\tfmt.Fprintln(os.Stderr, "usage: runner <cases.json> <start-index>")
\t\tos.Exit(2)
\t}
\ttext, err := os.ReadFile(os.Args[1])
\tif err != nil {
\t\tfmt.Fprintln(os.Stderr, "read cases file:", err)
\t\tos.Exit(2)
\t}
\tstart, err := strconv.Atoi(os.Args[2])
\tif err != nil {
\t\tfmt.Fprintln(os.Stderr, "parse start index:", err)
\t\tos.Exit(2)
\t}
\tvar cases []conformanceCase
\tif err := json.Unmarshal(text, &cases); err != nil {
\t\tfmt.Fprintln(os.Stderr, "parse cases file:", err)
\t\tos.Exit(2)
\t}

\temit(map[string]any{"ready": start})
\tfor i := start; i < len(cases); i++ {
\t\tc := cases[i]
\t\tvar outcome any
\t\tif check, ok := modules[c.Key]; ok {
\t\t\toutcome = runOne(check, c.Data)
\t\t} else {
\t\t\toutcome = map[string]string{"panic": "module not compiled"}
\t\t}
\t\t// The absolute index goes on the wire so stray output can't shift
\t\t// the harness's cursor.
\t\temit(map[string]any{"case": map[string]any{"i": i, "r": outcome}})
\t}
}

// os.Stdout is unbuffered, but sync anyway so a case that kills the
// process can't swallow the line before it.
func emit(v any) {
\tline, err := json.Marshal(v)
\tif err != nil {
\t\treturn
\t}
\tos.Stdout.Write(append(line, '\\n'))
\t_ = os.Stdout.Sync()
}
`;
}

/**
 * `# bakeoff/g_abc` package headers and
 * `g_abc/g_abc.go:12:3: message` diagnostics, blamed on the key whose
 * directory the file sits in. Only keys we wrote count: the toolchain
 * happily points at its own sources.
 */
function attributeGo(stderr, alive) {
  const live = new Set(alive);
  const errors = {};
  const unattributed = [];
  let current = null;
  for (const raw of stderr.split("\n")) {
    const line = raw.trimEnd();
    if (!line) continue;
    const header = line.match(/^#\s+(\S+)/);
    if (header) {
      const key = header[1].replace(`${GO_MODULE}/`, "");
      current = live.has(key) ? key : null;
      continue;
    }
    const span = line.match(/^\.?\/?([A-Za-z0-9_]+)\/[^:]+\.go:\d+(?::\d+)?:/);
    const key = span && live.has(span[1]) ? span[1] : current;
    if (key) {
      errors[key] = (errors[key] ?? "") + line.trimStart() + "\n";
    } else if (!/^\s*(too many errors|note:)/.test(line)) {
      unattributed.push(line);
    }
  }
  return { errors, unattributed };
}

function buildGo() {
  // Start clean: a package directory left over from an earlier batch
  // wouldn't be imported, but it would still be in the way.
  rmSync(batchDir, { recursive: true, force: true });
  mkdirSync(batchDir, { recursive: true });
  // A low `go` directive on purpose: nothing here needs more than `any`,
  // and a directive above the installed toolchain sends go off to download
  // one — which `GOPROXY=off` then refuses, turning every group into a
  // hard error on a machine whose Go is a release or two behind.
  writeFileSync(join(batchDir, "go.mod"), `module ${GO_MODULE}\n\ngo 1.21\n`);
  for (const key of keys) {
    const dir = join(batchDir, key);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, `${key}.go`), readFileSync(join(genDir, `${key}.go`)));
  }

  let alive = [...keys];
  const failures = {};
  let runner = [];
  for (let pass = 0; pass < MAX_PASSES; pass++) {
    writeFileSync(join(batchDir, "main.go"), goMain(alive));
    if (alive.length === 0) break;
    const out = spawnSync("go", ["build", "-o", "runner-bin", "."], {
      cwd: batchDir,
      env: goEnv,
      encoding: "utf8",
      maxBuffer: 256 * 1024 * 1024,
    });
    if (out.error) throw out.error;
    if (out.status === 0) {
      runner = [join(batchDir, "runner-bin")];
      break;
    }
    const { errors, unattributed } = attributeGo(out.stderr ?? "", alive);
    if (Object.keys(errors).length === 0) {
      // Nothing to drop, so this is our bug (bad main.go, bad go.mod)
      // rather than a bad schema.
      throw new Error(`go build failed with no attributable errors:\n${unattributed.join("\n")}\n${out.stdout ?? ""}`);
    }
    process.stderr.write(`go: dropping ${Object.keys(errors).length} module(s) after pass ${pass + 1}\n`);
    for (const [key, text] of Object.entries(errors)) {
      failures[key] ??= text.trimEnd();
    }
    alive = alive.filter((k) => !(k in errors));
  }
  if (alive.length > 0 && runner.length === 0) {
    throw new Error(`go build still failing after ${MAX_PASSES} passes (${alive.length} modules left)`);
  }
  emit(outcomesFor(keys, failures), runner);
}

// ---------------------------------------------------------- typescript

/**
 * `runner.ts`. `require`/`process` are declared rather than imported so
 * the batch needs no `@types/node` (and so `types: []` in the tsconfig
 * can keep tsc from going looking for ambient types).
 *
 * The suite's numbers are read back through `JSON.parse`'s reviver
 * `source`, which hands over the literal text of each number. quicktype's
 * TypeScript `Convert.toRoot` takes a JSON *string*, so without that the
 * digits would make a round trip through a float64 on the way in.
 */
function tsRunner(alive) {
  const imports = alive.map((k) => `import * as ${k} from "./${k}";`).join("\n");
  const table = alive.map((k) => `    "${k}": ${k}.__conformanceCheck,`).join("\n");
  return `// Generated by the bakeoff harness. See DESIGN.md for the runner protocol.
declare const require: any;
declare const process: any;
declare const Buffer: any;

${imports}

const fs: any = require("fs");

type Check = (json: string) => void;

const MODULES: { [key: string]: Check } = {
${table}
};

/** A number kept as the text the suite wrote, not as a float64. */
class RawNumber {
    constructor(public readonly text: string) {}
}

function parseCases(text: string): any {
    const reviver = function (_key: string, value: any, context?: any): any {
        if (typeof value === "number" && context && typeof context.source === "string") {
            return new RawNumber(context.source);
        }
        return value;
    };
    return JSON.parse(text, reviver as any);
}

/** JSON.stringify, but numbers come back out exactly as they went in. */
function rawStringify(value: any): string {
    if (value instanceof RawNumber) return value.text;
    if (value === null) return "null";
    if (Array.isArray(value)) return "[" + value.map(rawStringify).join(",") + "]";
    if (typeof value === "object") {
        const parts: string[] = [];
        for (const key of Object.keys(value)) {
            parts.push(JSON.stringify(key) + ":" + rawStringify(value[key]));
        }
        return "{" + parts.join(",") + "}";
    }
    return JSON.stringify(value);
}

function emit(value: any): void {
    // stdout is a pipe, where process.stdout.write is asynchronous and the
    // harness may be waiting on this very line. writeSync on a pipe can
    // stop short (and raise EAGAIN once the pipe is full), so loop: half a
    // line of JSON is a line the harness can't parse.
    const buf: any = Buffer.from(JSON.stringify(value) + "\\n", "utf8");
    let off = 0;
    while (off < buf.length) {
        try {
            off += fs.writeSync(1, buf, off, buf.length - off);
        } catch (e: any) {
            if (!e || e.code !== "EAGAIN") throw e;
        }
    }
}

function main(): void {
    const argv: string[] = process.argv;
    if (argv.length !== 4) {
        fs.writeSync(2, "usage: runner <cases.json> <start-index>\\n");
        process.exit(2);
    }
    const cases: any[] = parseCases(fs.readFileSync(argv[2], "utf8"));
    const start = parseInt(argv[3], 10);

    emit({ ready: start });
    for (let i = start; i < cases.length; i++) {
        const key: string = cases[i].key;
        let outcome: any;
        const check = MODULES[key];
        if (check === undefined) {
            outcome = { panic: "module not compiled" };
        } else {
            try {
                check(rawStringify(cases[i].data));
                outcome = "accept";
            } catch (e: any) {
                // Nothing a generated checker throws is distinguishable
                // from an ordinary mismatch, so everything caught here is
                // a reject; only a dead process counts as a panic, and
                // that one the harness sees for itself.
                outcome = { reject: e && e.message ? String(e.message) : String(e) };
            }
        }
        emit({ case: { i: i, r: outcome } });
    }
}

main();
`;
}

function tsconfig(alive) {
  return JSON.stringify(
    {
      compilerOptions: {
        target: "es2020",
        lib: ["es2020"],
        module: "commonjs",
        moduleResolution: "node",
        outDir: "out",
        rootDir: ".",
        strict: false,
        noImplicitAny: false,
        skipLibCheck: true,
        // No ambient type packages: the runner declares the two globals
        // it needs, and the generated modules import nothing.
        types: [],
        forceConsistentCasingInFileNames: false,
      },
      files: ["runner.ts", ...alive.map((k) => `${k}.ts`)],
    },
    null,
    2,
  );
}

/** `g_abc.ts(12,3): error TS2322: ...`, blamed on the file's stem. */
function attributeTs(output, alive) {
  const live = new Set(alive);
  const errors = {};
  const unattributed = [];
  let current = null;
  for (const raw of output.split("\n")) {
    const line = raw.trimEnd();
    if (!line) continue;
    const span = line.match(/^(?:\.[\\/])?(\S+?)\.ts\((\d+),(\d+)\):/);
    if (span) {
      const key = basename(span[1]);
      current = live.has(key) ? key : null;
    } else if (/^\S/.test(line)) {
      // A diagnostic with no file (TS18003, option errors) ends the run
      // of continuation lines belonging to the previous one.
      current = null;
    }
    if (current) {
      errors[current] = (errors[current] ?? "") + line + "\n";
    } else if (!/^(error TS18003|\s)/.test(line)) {
      unattributed.push(line);
    }
  }
  return { errors, unattributed };
}

function buildTs() {
  // tsc compiles whatever `files` lists, so a stale module from an
  // earlier batch would be ignored rather than harmful; clear it out
  // anyway so the batch directory says what was actually built.
  rmSync(batchDir, { recursive: true, force: true });
  mkdirSync(batchDir, { recursive: true });
  for (const key of keys) {
    writeFileSync(join(batchDir, `${key}.ts`), readFileSync(join(genDir, `${key}.ts`)));
  }
  // The batch lives under target/, which has no package.json, so Node
  // treats out/*.js as CommonJS. Say so rather than relying on it.
  mkdirSync(join(batchDir, "out"), { recursive: true });
  writeFileSync(join(batchDir, "out", "package.json"), '{ "type": "commonjs" }\n');

  const tsc = join(HERE, "node_modules", ".bin", "tsc");
  if (!existsSync(tsc)) throw new Error(`no tsc at ${tsc}`);

  let alive = [...keys];
  const failures = {};
  let runner = [];
  for (let pass = 0; pass < MAX_PASSES; pass++) {
    writeFileSync(join(batchDir, "runner.ts"), tsRunner(alive));
    writeFileSync(join(batchDir, "tsconfig.json"), tsconfig(alive));
    if (alive.length === 0) break;
    const out = spawnSync(tsc, ["--pretty", "false", "-p", join(batchDir, "tsconfig.json")], {
      cwd: batchDir,
      encoding: "utf8",
      maxBuffer: 256 * 1024 * 1024,
    });
    if (out.error) throw out.error;
    if (out.status === 0) {
      runner = [process.execPath, join(batchDir, "out", "runner.js")];
      break;
    }
    const text = `${out.stdout ?? ""}\n${out.stderr ?? ""}`;
    const { errors, unattributed } = attributeTs(text, alive);
    if (Object.keys(errors).length === 0) {
      throw new Error(`tsc failed with no attributable errors:\n${unattributed.join("\n")}`);
    }
    process.stderr.write(`tsc: dropping ${Object.keys(errors).length} module(s) after pass ${pass + 1}\n`);
    for (const [key, diag] of Object.entries(errors)) {
      failures[key] ??= diag.trimEnd();
    }
    alive = alive.filter((k) => !(k in errors));
  }
  if (alive.length > 0 && runner.length === 0) {
    throw new Error(`tsc still failing after ${MAX_PASSES} passes (${alive.length} modules left)`);
  }
  emit(outcomesFor(keys, failures), runner);
}

switch (target) {
  case "rust":
    buildRust();
    break;
  case "go":
    buildGo();
    break;
  case "typescript":
    buildTs();
    break;
  default:
    process.stderr.write(`build.mjs: unknown target ${target}\n`);
    process.exit(2);
}
